export function requireLovableApiKey() {
  const key = process.env.LOVABLE_API_KEY;
  if (!key) throw new Error("AI is not configured yet. Missing LOVABLE_API_KEY.");
  return key;
}

export function describeAiError(error: unknown) {
  const message = error instanceof Error ? error.message : String(error);
  if (message.includes("429")) {
    return "The AI assistant is busy right now (rate limit reached). Please try again in a moment.";
  }
  if (message.includes("402")) {
    return "AI credits are exhausted for this workspace. Add credits to keep generating.";
  }
  return message || "The AI request failed. Please try again.";
}